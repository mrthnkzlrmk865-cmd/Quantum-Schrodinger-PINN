def _cp(K, B, a):
    from scipy.stats import beta
    return (0.0 if K == 0 else float(beta.ppf(a / 2, K, B - K + 1)), 1.0 if K == B else float(beta.ppf(1 - a / 2, K + 1, B - K)))


def _holm_t(p, alpha):
    keys = sorted(p, key=p.get)
    rej = set()
    for i, k in enumerate(keys):
        if p[k] > alpha / (len(keys) - i):
            break
        rej.add(k)
    return rej


def make_tests_rows(D, K1_over=None, K2_over=None):
    st = D["statistics"]
    order = [(o, c["id"]) for o in st["observables"] for c in D["contrasts"]]
    B1, B2, a1, a2, al = st["B_stage1"], st["B_stage2"], st["mc_alpha_per_test_stage1"], st["mc_alpha_per_test_stage2"], st["holm_alpha"]
    K1 = {k: 50000 for k in order}
    for i in range(6):
        K1[order[i]] = 0                                    # clearly rejected
    K1[order[6]] = 60                                       # Stage-1 ambiguous, resolved at Stage 2
    K1[order[7]] = 75                                       # Stage-1 ambiguous, still ambiguous after Stage 2
    K1.update(K1_over or {})
    K2 = {order[6]: 500, order[7]: 800}
    K2.update(K2_over or {})
    v1 = {k: _cp(K1[k], B1, a1) for k in order}
    p1lo = {k: v1[k][0] for k in order}
    p1hi = {k: max(v1[k][1], (K1[k] + 1) / (B1 + 1)) for k in order}
    A1 = _holm_t(p1lo, al) - _holm_t(p1hi, al)
    rows = {}
    for k in order:
        stage, K, B, a = (2, K2.get(k, 10 * K1[k]), B2, a2) if k in A1 else (1, K1[k], B1, a1)
        ph = (K + 1) / (B + 1)
        lo, hi = _cp(K, B, a)
        rows[k] = dict(observable=k[0], contrast_id=k[1], theta_hat=0.01, ci95_sampling_lo=-0.005, ci95_sampling_hi=0.025, K_stage1=K1[k], K=K, B=B,
                       stage=stage, p_hat=ph, mc_se=math.sqrt(ph * (1 - ph) / B), mc_ci_sim99_lo=lo, mc_ci_sim99_hi=hi, p_lo_final=lo, p_hi_final=max(hi, ph),
                       **rng_meta(stage))
    phi = {k: rows[k]["p_hi_final"] for k in order}
    R = _holm_t(phi, al)
    A = _holm_t({k: rows[k]["p_lo_final"] for k in order}, al) - R
    ranked = sorted(order, key=lambda k: (phi[k], order.index(k)))
    adj = 0.0
    for i, k in enumerate(ranked):
        adj = max(adj, min(1.0, (len(order) - i) * phi[k]))
        rows[k].update(holm_rank=i + 1, holm_threshold=al / (len(order) - i), p_holm_adj_from_phi=adj,
                       decision=st["decisions"][0] if k in R else st["decisions"][2] if k in A else st["decisions"][1])
    return [rows[k] for k in order], dict(A1=A1, R=R, A=A, order=order)


